package com.github.br.libgdx.jam36.screens.phase;

public class Choose {

    private final int id;
    private final String text;

    public Choose(int id, String text) {
        this.id = id;
        this.text = text;
    }

    public int getId() {
        return id;
    }

    public String getText() {
        return text;
    }

}
